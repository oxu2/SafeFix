def get_available_gpus():
    return list(range(torch.cuda.device_count()))

def configure_gpu_memory(available_gpus, max_memory_per_gpu_gb=23):
    max_memory = {}
    max_memory_str = f"{max_memory_per_gpu_gb}GiB"
    for gpu_id in available_gpus:
        max_memory[gpu_id] = max_memory_str
    if not max_memory:
        print("Warning: No GPUs available. Using CPU.")
        return "cpu"
    print(f"Using {len(max_memory)} GPU(s) with {max_memory_str} memory allocation each")
    return max_memory

