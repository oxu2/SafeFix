def build_prompt(attr_name, attr_info):
    """Build a multiple-choice prompt for the given attribute."""
    word_list = attr_info.get('word', [])
    words_str = ", ".join(word_list)
    template = ATTRIBUTE_QUESTIONS.get(attr_name)
    if template is not None:
        return template.format(words=words_str)

    question = str(attr_info.get('question', '') or '').strip()
    if question:
        return (
            f"{question} "
            f"Choose exactly one from [{words_str}]. "
            "Reply with ONLY the chosen option."
        )

    template = (
        "Describe the {attr} of the main person or subject in this image. "
        "Choose exactly one from: {words}. "
        "Answer with only the chosen option, nothing else."
    )
    return template.format(attr=attr_name, words=words_str)


def parse_answer(response, word_list):
    """
    Parse VLM response and match it to one of the candidate words.
    Returns the matched word, or None if no match is found.
    """
    # Clean up: take only the first line, strip punctuation and whitespace
    first_line = response.split('\n')[0].strip().rstrip('.').strip()
    response_lower = first_line.lower()

    # 1. Direct match
    for word in word_list:
        if response_lower == word.lower():
            return word

    # 2. Prefix match (handles garbled output like "plastic\ngarbage...")
    sorted_words = sorted(word_list, key=len, reverse=True)
    for word in sorted_words:
        if response_lower.startswith(word.lower()):
            return word

    # 3. Substring match (candidate word appears inside response)
    for word in sorted_words:
        if word.lower() in response_lower:
            return word

    # 4. First-word match
    first_word = response_lower.split()[0] if response_lower.split() else ""
    for word in word_list:
        if first_word == word.lower():
            return word

    # 5. Ask Qwen (text-only, no image) to pick the closest word from the list
    return None


def remap_with_vlm(bad_answer, word_list):
    """
    Ask the VLM (text-only) to map an invalid answer to the closest word in the list.
    """
    words_str = ", ".join(word_list)
    prompt = (
        f"The word '{bad_answer}' is not in this list: [{words_str}]. "
        f"Which word in the list is closest in meaning to '{bad_answer}'? "
        f"Reply with ONLY the chosen option from the list."
    )

    if is_internvl:
        generation_config = dict(max_new_tokens=10, do_sample=False)
        remap_response = model.chat(tokenizer, None, prompt, generation_config)
    else:
        messages = [
            {"role": "system", "content": "You are a helpful assistant."},
            {"role": "user", "content": prompt},
        ]
        text = processor.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
        inputs = processor(text=[text], padding=True, return_tensors="pt")
        inputs = inputs.to('cuda')
        output_ids = model.generate(**inputs, max_new_tokens=10, do_sample=False, temperature=None)
        generated_ids = [
            output_ids[len(input_ids):]
            for input_ids, output_ids in zip(inputs.input_ids, output_ids)
        ]
        remap_response = processor.batch_decode(
            generated_ids, skip_special_tokens=True, clean_up_tokenization_spaces=True
        )[0].strip()

    # Try to match the remap response
    remap_lower = remap_response.split('\n')[0].strip().rstrip('.').lower()
    for word in word_list:
        if remap_lower == word.lower():
            return word
    sorted_words = sorted(word_list, key=len, reverse=True)
    for word in sorted_words:
        if word.lower() in remap_lower:
            return word

    # If even the remap fails, return the first word
    return word_list[0]


def _has_valid_person_annotation(annotations):
    for ann in annotations:
        if ann.get("category_id") != 1:
            continue
        if ann.get("iscrowd", 0) == 1:
            continue

        bbox = ann.get("bbox", [0, 0, 0, 0])
        if bbox[2] <= 1 or bbox[3] <= 1:
            continue

        keypoints = ann.get("keypoints", [])
        if len(keypoints) != 51:
            continue
        visible = sum(1 for i in range(2, len(keypoints), 3) if keypoints[i] > 0)
        if visible > 0:
            return True
    return False


def collect_folder_dataset(root_dir):
    classes = sorted([d for d in os.listdir(root_dir) if os.path.isdir(os.path.join(root_dir, d))])
    class_to_idx = {cls: idx for idx, cls in enumerate(classes)}
    print(f"Found {len(classes)} classes: {classes}")

    all_datas = []
    labels = []
    sample_rows = []
    for class_name in sorted(os.listdir(root_dir)):
        class_dir = os.path.join(root_dir, class_name)
        if not os.path.isdir(class_dir):
            continue
        for fname in os.listdir(class_dir):
            if fname.lower().endswith(('.jpg', '.jpeg', '.png', '.bmp', '.tiff')):
                image_path = os.path.join(class_dir, fname)
                label = class_to_idx[class_name]
                labels.append(label)
                all_datas.append(image_path)
                sample_rows.append({
                    'image_path': image_path,
                    'image_id': '',
                    'file_name': fname,
                })

    return all_datas, labels, sample_rows


def collect_coco_pose_single_split(coco_root, split, annotation_file=None, image_dir=None):
    split_name = f'{split}2017'
    resolved_annotation_file = annotation_file or os.path.join(
        coco_root, 'annotations', f'person_keypoints_{split_name}.json'
    )
    resolved_image_dir = image_dir or os.path.join(coco_root, split_name)

    with open(resolved_annotation_file, 'r') as f:
        coco_data = json.load(f)

    image_lookup = {img['id']: img for img in coco_data.get('images', [])}
    annotations_by_image = {}
    for ann in coco_data.get('annotations', []):
        annotations_by_image.setdefault(ann['image_id'], []).append(ann)

    valid_image_ids = [
        image_id
        for image_id in sorted(image_lookup)
        if _has_valid_person_annotation(annotations_by_image.get(image_id, []))
    ]

    all_datas = []
    labels = []
    sample_rows = []
    missing_files = 0
    for image_id in valid_image_ids:
        image_info = image_lookup.get(image_id)
        if image_info is None:
            continue
        image_path = os.path.join(resolved_image_dir, image_info['file_name'])
        if not os.path.exists(image_path):
            missing_files += 1
            continue
        all_datas.append(image_path)
        labels.append(1)
        sample_rows.append({
            'image_path': image_path,
            'image_id': image_id,
            'file_name': image_info['file_name'],
            'split': split,
        })

    print(
        f"Loaded COCO pose split '{split}' from {resolved_annotation_file}: "
        f"{len(all_datas)} valid images"
        + (f" ({missing_files} missing files skipped)" if missing_files else "")
    )
    return all_datas, labels, sample_rows


def collect_coco_pose_dataset(coco_root, split, annotation_file=None, image_dir=None):
    if split != 'all':
        return collect_coco_pose_single_split(
            coco_root=coco_root,
            split=split,
            annotation_file=annotation_file,
            image_dir=image_dir,
        )

    if annotation_file is not None or image_dir is not None:
        raise ValueError('--annotation_file and --image_dir are only supported with a single COCO split')

    all_datas = []
    labels = []
    sample_rows = []
    for single_split in ('train', 'val'):
        split_datas, split_labels, split_rows = collect_coco_pose_single_split(
            coco_root=coco_root,
            split=single_split,
        )
        all_datas.extend(split_datas)
        labels.extend(split_labels)
        sample_rows.extend(split_rows)
    return all_datas, labels, sample_rows


def load_processed_coco_csv(csv_path, attr_names):
    if not os.path.exists(csv_path):
        return {}

    processed = {}
    with open(csv_path, 'r', newline='', encoding='utf-8') as handle:
        reader = csv.DictReader(handle)
        for row in reader:
            image_id = row.get('image_id', '').strip()
            if not image_id:
                continue
            values = {}
            complete = True
            for attr_name in attr_names:
                value = row.get(attr_name, '').strip()
                if not value:
                    complete = False
                    break
                values[attr_name] = value
            if complete:
                processed[image_id] = values
    return processed


def write_attribute_csv(csv_path, sample_rows, attributes_dict, attr_names, dataset_name, only_completed=False):
    fieldnames = ['image_id', *attr_names]

    with open(csv_path, 'w', newline='', encoding='utf-8') as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        for index, sample_row in enumerate(sample_rows):
            if only_completed and not all(attributes_dict[attr_name]['data'][index] for attr_name in attr_names):
                continue
            row = {
                'image_id': sample_row.get('image_id', '') or sample_row.get('file_name', '') or str(index),
            }
            for attr_name in attr_names:
                row[attr_name] = attributes_dict[attr_name]['data'][index]
            writer.writerow(row)


def collect_kitti_dataset(kitti_root, split='train'):
    import glob
    all_datas = []
    labels = []
    sample_rows = []

    if split == 'all':
        search_path = os.path.join(kitti_root, 'images', '**', '*.*')
        image_paths = sorted(glob.glob(search_path, recursive=True))
    else:
        split_dir = os.path.join(kitti_root, 'images', split)
        if not os.path.isdir(split_dir):
            raise FileNotFoundError(f"KITTI split directory not found: {split_dir}")
        search_path = os.path.join(split_dir, '*.*')
        image_paths = sorted(glob.glob(search_path))

    image_paths = [p for p in image_paths if p.lower().endswith(('.jpg', '.jpeg', '.png'))]
    for i, image_path in enumerate(image_paths):
        fname = os.path.basename(image_path)
        all_datas.append(image_path)
        labels.append(1)
        sample_rows.append({
            'image_path': image_path,
            'image_id': fname.split('.')[0],
            'file_name': fname,
            'split': split
        })
    print(f"Found {len(all_datas)} images in KITTI dataset at {kitti_root} (split={split})")
    return all_datas, labels, sample_rows


