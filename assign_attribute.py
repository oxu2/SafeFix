ATTRIBUTE_QUESTIONS = {
    "color": (
        "What is the dominant color of the main object in this image? "
        "You MUST choose exactly one from the following list: [{words}]. "
        "Do NOT answer with any word outside this list. "
        "Reply with ONLY that single word."
    ),
    "background": (
        "What is the background of this image? "
        "You MUST choose exactly one from the following list: [{words}]. "
        "Do NOT answer with any word outside this list. "
        "Reply with ONLY that single word."
    ),
    "texture": (
        "What material or texture is the main object in this image? "
        "You MUST choose exactly one from the following list: [{words}]. "
        "Do NOT answer with any word outside this list. "
        "Reply with ONLY that single word."
    ),
}


def build_prompt(attr_name, word_list):
    """Build a multiple-choice prompt for the given attribute."""
    words_str = ", ".join(word_list)
    template = ATTRIBUTE_QUESTIONS.get(attr_name)
    if template is None:
        # Fallback for unknown attributes
        template = (
            "Describe the {attr} of the main subject in this image. "
            "Choose exactly one from: {words}. "
            "Answer with only the chosen word, nothing else."
        )
        return template.format(attr=attr_name, words=words_str)
    return template.format(words=words_str)


def parse_answer(response, word_list):
    """
    Parse VLM response and match it to one of the candidate words.
    Returns the matched word, or None if no match is found.
    """
    # Clean up: take only the first line, strip punctuation and whitespace
    first_line = response.split('\n')[0].strip().rstrip('.').strip()
    response_lower = first_line.lower()

    # 1. Direct match
    for word in word_list:
        if response_lower == word.lower():
            return word

    # 2. Prefix match (handles garbled output like "plastic\ngarbage...")
    sorted_words = sorted(word_list, key=len, reverse=True)
    for word in sorted_words:
        if response_lower.startswith(word.lower()):
            return word

    # 3. Substring match (candidate word appears inside response)
    for word in sorted_words:
        if word.lower() in response_lower:
            return word

    # 4. First-word match
    first_word = response_lower.split()[0] if response_lower.split() else ""
    for word in word_list:
        if first_word == word.lower():
            return word

    # 5. Ask Qwen (text-only, no image) to pick the closest word from the list
    return None


def remap_with_vlm(bad_answer, word_list):
    """
    Ask the VLM (text-only) to map an invalid answer to the closest word in the list.
    """
    words_str = ", ".join(word_list)
    prompt = (
        f"The word '{bad_answer}' is not in this list: [{words_str}]. "
        f"Which word in the list is closest in meaning to '{bad_answer}'? "
        f"Reply with ONLY that single word from the list."
    )

    if is_internvl:
        generation_config = dict(max_new_tokens=10, do_sample=False)
        remap_response = model.chat(tokenizer, None, prompt, generation_config)
    else:
        messages = [
            {"role": "system", "content": "You are a helpful assistant."},
            {"role": "user", "content": prompt},
        ]
        text = processor.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
        inputs = processor(text=[text], padding=True, return_tensors="pt")
        inputs = inputs.to('cuda')
        output_ids = model.generate(**inputs, max_new_tokens=10, do_sample=False, temperature=None)
        generated_ids = [
            output_ids[len(input_ids):]
            for input_ids, output_ids in zip(inputs.input_ids, output_ids)
        ]
        remap_response = processor.batch_decode(
            generated_ids, skip_special_tokens=True, clean_up_tokenization_spaces=True
        )[0].strip()

    # Try to match the remap response
    remap_lower = remap_response.split('\n')[0].strip().rstrip('.').lower()
    for word in word_list:
        if remap_lower == word.lower():
            return word
    sorted_words = sorted(word_list, key=len, reverse=True)
    for word in sorted_words:
        if word.lower() in remap_lower:
            return word

    # If even the remap fails, return the first word
    return word_list[0]


