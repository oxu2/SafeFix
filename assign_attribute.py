def configure_gpu_memory(available_gpus, max_memory_per_gpu_gb=23):
    max_memory = {}
    max_memory_str = f"{max_memory_per_gpu_gb}GiB"
    for gpu_id in available_gpus:
        max_memory[gpu_id] = max_memory_str
