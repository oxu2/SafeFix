def inference(image_path, prompt, sys_prompt="You are a helpful assistant.", max_new_tokens=10):
    """Run VLM inference on a single image with a text prompt."""
    if is_internvl:
        return _inference_internvl(image_path, prompt, max_new_tokens)
    else:
        return _inference_qwen(image_path, prompt, sys_prompt, max_new_tokens)

def _inference_qwen(image_path, prompt, sys_prompt, max_new_tokens):
    """Qwen2.5-VL / Qwen3-VL inference."""
    image = Image.open(image_path).convert("RGB")
    image.thumbnail([640, 640], Image.Resampling.LANCZOS)
    image_local_path = "file://" + os.path.abspath(image_path)

    if is_qwen3:
        messages = [
            {"role": "system", "content": sys_prompt},
            {"role": "user", "content": [
                {"type": "image", "url": image_local_path},
                {"type": "text", "text": prompt},
            ]},
        ]
    else:
        messages = [
            {"role": "system", "content": sys_prompt},
            {"role": "user", "content": [
                {"type": "text", "text": prompt},
                {"image": image_local_path},
            ]},
        ]

    text = processor.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
    inputs = processor(
        text=[text], images=[image], padding=True, return_tensors="pt"
    ).to('cuda')
    output_ids = model.generate(**inputs, max_new_tokens=max_new_tokens, do_sample=False, temperature=None)
    generated_ids = [
        output_ids[len(input_ids):]
        for input_ids, output_ids in zip(inputs.input_ids, output_ids)
    ]
    output_text = processor.batch_decode(
        generated_ids, skip_special_tokens=True, clean_up_tokenization_spaces=True
    )
    return output_text[0].strip()

def _inference_internvl(image_path, prompt, max_new_tokens):
    """InternVL2 inference using model.chat()."""
    pixel_values = load_internvl_image(image_path, max_num=6).to(torch.bfloat16).cuda()
    generation_config = dict(max_new_tokens=max_new_tokens, do_sample=False)
    question = f'<image>\n{prompt}'
    response = model.chat(tokenizer, pixel_values, question, generation_config)
    return response.strip()


